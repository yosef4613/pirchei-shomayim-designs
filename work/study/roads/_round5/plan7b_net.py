# The cross-section of each class: walk | lanes | median | lanes | walk (m); halfW = half the total width in px (10 px = 1 m).
def xs(walk, lanes_dir, median, lane=3.9, both=True):
    w = 2 * walk + (2 if both else 1) * lanes_dir * lane + median
    return dict(walk_m=walk, lane_m=lane, dirN=lanes_dir, twoway=both, median_m=median, width_m=round(w, 1), halfW=round(w * 10 / 2, 1))
